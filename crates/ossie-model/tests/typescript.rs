//! The TypeScript package (`packages/sem`) is generated from this crate's
//! types by ts-rs, and committed. This test regenerates it and fails when the
//! committed files differ; `UPDATE_BINDINGS=1` writes them instead:
//!
//! ```sh
//! UPDATE_BINDINGS=1 cargo test -p ossie-model --features ts --test typescript
//! ```
//!
//! It also writes every fixture, as this crate serializes it, as a TypeScript
//! module whose value `satisfies` its document type. The package's
//! `typecheck` then proves real documents fit the types, unknown keys
//! included.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use ossie_model::{
    MAPPING_SPEC_VERSION, MappingDocument, ONTOLOGY_SPEC_VERSION, OSSIE_SPEC_VERSION,
    OntologyDocument, OssieDocument, parser,
};
use ts_rs::{Config, TS};

const HEADER: &str = "// Generated by crates/ossie-model/tests/typescript.rs. Do not edit.\n";

fn package() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../packages/sem")
}

/// The generated directories, relative to the package.
const GENERATED: [&str; 2] = ["src/generated", "test/fixtures"];

/// Every generated file, by path relative to the package.
fn expected() -> BTreeMap<PathBuf, String> {
    let mut files = types();
    files.extend(fixtures());
    files
}

/// One file per type, plus an index re-exporting them with the spec versions.
fn types() -> BTreeMap<PathBuf, String> {
    let out = std::env::temp_dir().join(format!("ossie-model-ts-{}", std::process::id()));
    let _ = fs::remove_dir_all(&out);
    let cfg = Config::new()
        .with_out_dir(&out)
        .with_import_extension(Some("js"));
    OssieDocument::export_all(&cfg).expect("export OssieDocument");
    OntologyDocument::export_all(&cfg).expect("export OntologyDocument");
    MappingDocument::export_all(&cfg).expect("export MappingDocument");

    let mut files = read_tree(&out, Path::new("src/generated"));
    fs::remove_dir_all(&out).expect("clean up exported types");

    let mut index = format!(
        "{HEADER}\nexport const OSSIE_SPEC_VERSION = {OSSIE_SPEC_VERSION:?};\n\
         export const ONTOLOGY_SPEC_VERSION = {ONTOLOGY_SPEC_VERSION:?};\n\
         export const MAPPING_SPEC_VERSION = {MAPPING_SPEC_VERSION:?};\n\n"
    );
    for path in files.keys() {
        let module = path
            .strip_prefix("src/generated")
            .unwrap()
            .with_extension("js");
        index.push_str(&format!("export type * from \"./{}\";\n", module.display()));
    }
    files.insert(PathBuf::from("src/generated/index.ts"), index);
    files
}

/// Each fixture as a module whose default export satisfies its document type.
fn fixtures() -> BTreeMap<PathBuf, String> {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures");
    let mut files = BTreeMap::new();
    for entry in fs::read_dir(&dir).expect("read fixtures") {
        let path = entry.expect("fixture entry").path();
        let name = path.file_name().unwrap().to_str().unwrap().to_owned();
        let Some(stem) = name.strip_suffix(".yaml") else {
            continue;
        };
        let yaml = fs::read_to_string(&path).expect("read fixture");
        let (ty, json) = if stem.ends_with(".ontology") {
            let doc = parsed(&name, parser::ontology_from_yaml_str(&yaml));
            ("OntologyDocument", serde_json::to_string_pretty(&doc))
        } else if stem.ends_with(".mapping") {
            let doc = parsed(&name, parser::mapping_from_yaml_str(&yaml));
            ("MappingDocument", serde_json::to_string_pretty(&doc))
        } else {
            let doc = parsed(&name, parser::from_yaml_str(&yaml));
            ("OssieDocument", serde_json::to_string_pretty(&doc))
        };
        let json = json.expect("serialize fixture");
        files.insert(
            Path::new("test/fixtures").join(format!("{stem}.ts")),
            format!(
                "{HEADER}// Source: crates/ossie-model/tests/fixtures/{name}\n\n\
                 import type {{ {ty} }} from \"../../src/index.js\";\n\n\
                 export default {json} satisfies {ty};\n"
            ),
        );
    }
    files
}

fn parsed<T>(name: &str, result: Result<T, ossie_model::Error>) -> T {
    result.unwrap_or_else(|e| panic!("{name}: {e}"))
}

/// Every file now in the generated directories.
fn committed() -> BTreeMap<PathBuf, String> {
    GENERATED
        .iter()
        .flat_map(|dir| read_tree(&package().join(dir), Path::new(dir)))
        .collect()
}

/// Every file under `root`, keyed by its path under `prefix`. A missing
/// directory has no files.
fn read_tree(root: &Path, prefix: &Path) -> BTreeMap<PathBuf, String> {
    let mut files = BTreeMap::new();
    let Ok(entries) = fs::read_dir(root) else {
        return files;
    };
    for entry in entries {
        let path = entry.expect("directory entry").path();
        let key = prefix.join(path.file_name().unwrap());
        if path.is_dir() {
            files.extend(read_tree(&path, &key));
        } else {
            files.insert(key, fs::read_to_string(&path).expect("read file"));
        }
    }
    files
}

#[test]
fn the_typescript_package_is_up_to_date() {
    let expected = expected();

    if std::env::var_os("UPDATE_BINDINGS").is_some() {
        for dir in GENERATED {
            let _ = fs::remove_dir_all(package().join(dir));
            fs::create_dir_all(package().join(dir)).expect("create generated directory");
        }
        for (path, text) in &expected {
            let path = package().join(path);
            fs::create_dir_all(path.parent().unwrap()).expect("create generated directory");
            fs::write(path, text).expect("write generated file");
        }
        return;
    }

    let committed = committed();
    let stale: Vec<String> = expected
        .keys()
        .chain(committed.keys())
        .filter(|path| expected.get(*path) != committed.get(*path))
        .map(|path| path.display().to_string())
        .collect::<std::collections::BTreeSet<_>>()
        .into_iter()
        .collect();
    assert!(
        stale.is_empty(),
        "packages/sem is out of date in {stale:?}; regenerate it with\n  \
         UPDATE_BINDINGS=1 cargo test -p ossie-model --features ts --test typescript"
    );
}
